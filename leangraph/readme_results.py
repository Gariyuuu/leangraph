"""Write the headline results table into README.md from the frozen analysis (no hand-typed numbers).

    python -m leangraph.readme_results --run-id main

Replaces the block between <!-- results:start --> and <!-- results:end -->; appends one if absent.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- results:start -->", "<!-- results:end -->"
from .labels import CONFIG_LABELS as NAMES  # noqa: E402


def render(summary: dict, run_id: str) -> str:
    rows = sorted(summary["configs"].items(), key=lambda kv: -kv[1]["rate"])
    n = max((m["n"] for _, m in rows), default=0)
    out = [START, f"## Results (run `{run_id}`, {n} test theorems)", ""]
    # Same data-driven interim note as the site banner and the paper's status paragraph.
    from .export_site import run_status
    from .run import MAIN_GRID
    st = run_status(summary, summary.get("n_tasks", n), MAIN_GRID)
    if not st["final"]:
        pending = [f"{NAMES.get(r['config'], r['config'])} ({r['done']}/{r['total']})"
                   for r in st["configs"] if r["state"] != "complete"]
        out += [f"**Interim:** {st['complete']} of {st['expected']} configurations are complete. Still running: "
                f"{', '.join(pending)}. Only complete configurations and contrasts between them are shown; every "
                "number is recomputed when the grid finishes.", ""]
    out += ["| Configuration | Verified | Rate [95% CI] | Cost / verified |", "|---|---:|---:|---:|"]
    for c, m in rows:
        cpv = f"${m['cost_per_verified']:.4f}" if m.get("cost_per_verified") else "—"
        out.append(f"| {NAMES.get(c, c)} | {m['verified']}/{m['n']} | {100 * m['rate']:.1f}% "
                   f"[{100 * m['ci'][0]:.1f}, {100 * m['ci'][1]:.1f}] | {cpv} |")
    sig = [c for c in summary["contrasts"] if c["p_holm"] < 0.05]
    if summary["contrasts"]:
        out += ["", f"Paired contrasts (exact McNemar, Holm-adjusted across {len(summary['contrasts'])}): "
                f"{len(sig)} significant at 0.05."]
        for c in summary["contrasts"]:
            out.append(f"- {c['question']}: {100 * c['diff']:+.1f} points "
                       f"[{100 * c['diff_ci'][0]:+.1f}, {100 * c['diff_ci'][1]:+.1f}], Holm p = {c['p_holm']:.3g}")
    out += ["", "Generated by `python -m leangraph.readme_results`; details in the paper and on the site.", END]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", default="main")
    run_id = ap.parse_args().run_id
    summary = json.loads((ROOT / "results" / "analysis" / run_id / "summary.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = render(summary, run_id)
    if START in text and END in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        anchor = "## Layout"
        text = text.replace(anchor, block + "\n\n" + anchor, 1) if anchor in text else text + "\n\n" + block + "\n"
    readme.write_text(text)
    print(f"README results block written from results/analysis/{run_id}/summary.json")


if __name__ == "__main__":
    main()
